import { deepStrictEqual, equal, ok } from "node:assert/strict";
import { mkdtemp, readdir, symlink, writeFile } from "node:fs/promises";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { test } from "node:test";
import {
	cleanupClipboardImages,
	isPiClipboardImageFile,
} from "../cleanup.ts";

const generatedPng = "pi-clipboard-123e4567-e89b-12d3-a456-426614174000.png";
const generatedJpeg = "pi-clipboard-123e4567-e89b-12d3-a456-426614174001.jpeg";

async function temporaryFixture(): Promise<string> {
	return mkdtemp(join(tmpdir(), "pi-clipboard-cleanup-test-"));
}

test("recognizes only Pi clipboard image names", () => {
	ok(isPiClipboardImageFile(generatedPng));
	ok(isPiClipboardImageFile(generatedJpeg));
	ok(!isPiClipboardImageFile("pi-clipboard-not-a-uuid.png"));
	ok(!isPiClipboardImageFile("pi-clipboard-123e4567-e89b-12d3-a456-426614174000.txt"));
	ok(!isPiClipboardImageFile("other-tool-123e4567-e89b-12d3-a456-426614174000.png"));
});

test("deletes generated images and preserves unrelated files", async () => {
	const directory = await temporaryFixture();
	await writeFile(join(directory, generatedPng), "png");
	await writeFile(join(directory, generatedJpeg), "jpeg");
	await writeFile(join(directory, "keep-me.png"), "not generated by Pi");
	await writeFile(join(directory, "pi-clipboard-not-a-uuid.png"), "not generated by Pi");

	const result = await cleanupClipboardImages(directory);

	equal(result.matched, 2);
	deepStrictEqual(result.deleted.sort(), [generatedJpeg, generatedPng].sort());
	deepStrictEqual(result.failed, []);
	deepStrictEqual((await readdir(directory)).sort(), [
		"keep-me.png",
		"pi-clipboard-not-a-uuid.png",
	]);
});

test("does not remove a matching name when it is a symlink", async () => {
	const directory = await temporaryFixture();
	const target = join(directory, "target.png");
	await writeFile(target, "target");
	await symlink(target, join(directory, generatedPng));

	const result = await cleanupClipboardImages(directory);

	equal(result.matched, 0);
	equal(result.deleted.length, 0);
	equal((await readdir(directory)).includes(generatedPng), true);
});
